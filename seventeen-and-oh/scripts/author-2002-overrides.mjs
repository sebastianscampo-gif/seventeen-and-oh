// apply-overrides precedence (last match wins).
const existing = readCsv(OVERRIDES);
const kept = existing.filter((r) => r.season !== SEASON);

const merged = [...kept, ...newRows];
writeCsv(OVERRIDES, merged, OVERRIDE_COLUMNS);

